bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed)
        switch (keycode) {
        case INSTAQUOTE:
                SEND_STRING("\' ");
                return false;
        case INSTADOUBLE:
                SEND_STRING("\" ");
                return false;
        case INSTACIRC:
                SEND_STRING("^ ");
                return false;
        case INSTAGRAVE:
                SEND_STRING("` ");
                return false;
        }
    return true;
}

